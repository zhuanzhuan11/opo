import {execFileSync} from 'node:child_process';
import {existsSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const app=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const git=(...args)=>execFileSync('git',['-C',app,...args],{maxBuffer:64*1024*1024});
if(git('status','--porcelain','--untracked-files=all').toString().trim())throw Error('Commit reviewed preparation files before packaging; working tree must be clean');
const sha=git('rev-parse','HEAD').toString().trim();
const output=resolve(process.argv[2]||resolve(app,'../../output',`OPO2.0-predeployment-${sha.slice(0,12)}.zip`));
const manifest=output+'.manifest.json';
if(existsSync(output)||existsSync(manifest))throw Error('Output already exists; choose a new destination');
const files=git('ls-tree','-r','--name-only','HEAD').toString().trim().split('\n');
const forbidden=files.filter(p=>p!=='frontend/downloads/opo-node-resource-output-v1.1.pdf'&&p!=='frontend/downloads/opo-node-dividends-step-guide-v1.0.pdf'&&/(^|\/)(review|node_modules|\.secrets|backups|test-results)(\/|$)|\.(db|sqlite|pdf|pem|key)$|(^|\/)\.env($|\.)/.test(p)&&!p.endsWith('.env.example')&&!p.endsWith('.env.catalog.example'));
if(forbidden.length)throw Error('Review excluded package paths: '+forbidden.join(', '));
mkdirSync(dirname(output),{recursive:true});
git('archive','--format=zip','--prefix=opo-release/','-o',output,'HEAD');
const checksum=b=>createHash('sha256').update(b).digest('hex');
const entries=files.map(path=>({path,sha256:checksum(git('show',`HEAD:${path}`))}));
writeFileSync(manifest,JSON.stringify({sourceCommit:sha,zipSha256:checksum(readFileSync(output)),scope:'Local preparation only; no deployment or production certification',files:entries},null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({output,manifest,sourceCommit:sha,files:entries.length}));
